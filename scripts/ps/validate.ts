// Builds AU Patient Summary documents for three cohort patients from a FHIR server and validates them with
// the HL7 validator against hl7.fhir.au.ps#1.0.0. Writes docs/validation/au-ps.md.
// Usage: npm run validate:ps            (local HAPI on localhost:8080, `npm run load` first)
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import type {
  AllergyIntolerance,
  Bundle,
  Condition,
  Immunization,
  Medication,
  MedicationRequest,
  Observation,
  OperationOutcome,
  Patient,
  Practitioner,
} from "fhir/r4";
import { buildPatientSummary } from "../../src/lib/ps/build.ts";

const FHIR = process.env.FHIR_BASE_URL ?? "http://localhost:8080/fhir";
const WORK = ".cache/ps";
const JAR = ".cache/validator_cli.jar";
const TX = "https://tx.dev.hl7.org.au/fhir";

async function all<T>(q: string): Promise<T[]> {
  const out: T[] = [];
  let next: string | undefined = `${FHIR}/${q}`;
  while (next) {
    const b = (await (await fetch(next)).json()) as Bundle;
    out.push(...((b.entry ?? []).map((e) => e.resource) as T[]));
    next = b.link?.find((l) => l.relation === "next")?.url;
  }
  return out;
}

async function practitioners(meds: (MedicationRequest | Medication)[]) {
  const ids = [
    ...new Set(
      meds.flatMap((m) =>
        m.resourceType === "MedicationRequest" ? [m.requester?.reference?.split("/")[1] ?? ""] : [],
      ),
    ),
  ].filter(Boolean);
  return ids.length ? all<Practitioner>(`Practitioner?_id=${ids.join(",")}`) : [];
}

async function source(id: string) {
  const meds = await all<MedicationRequest | Medication>(
    `MedicationRequest?patient=${id}&status=active&_include=MedicationRequest:medication&_count=100`,
  );
  return {
    patient: (await (await fetch(`${FHIR}/Patient/${id}`)).json()) as Patient,
    conditions: await all<Condition>(`Condition?patient=${id}&_count=100`),
    allergies: await all<AllergyIntolerance>(`AllergyIntolerance?patient=${id}`),
    medications: meds.filter((r): r is MedicationRequest => r.resourceType === "MedicationRequest"),
    medicationById: new Map(
      meds.flatMap((r) => (r.resourceType === "Medication" ? [[r.id!, r] as const] : [])),
    ),
    immunizations: await all<Immunization>(`Immunization?patient=${id}&_count=100`),
    practitioners: await practitioners(meds),
    results: await all<Observation>(`Observation?patient=${id}&category=laboratory&_count=200`),
  };
}

const patients = (await all<Patient>("Patient?_count=50&_sort=family")).slice(0, 3);
mkdirSync(WORK, { recursive: true });
const files: { file: string; label: string }[] = [];
for (const [i, p] of patients.entries()) {
  const src = await source(p.id!);
  const noAllergies = i === 2; // the cohort has no patient without allergy records, so the third has them removed
  if (noAllergies) src.allergies = [];
  const file = `${WORK}/summary-${i + 1}.json`;
  writeFileSync(file, JSON.stringify(buildPatientSummary(src, new Date("2026-11-14T00:00:00Z")), null, 2));
  files.push({
    file,
    label: `${p.name?.[0]?.family}${noAllergies ? " (allergies removed to test the empty-section rule)" : ""}`,
  });
}

const out = `${WORK}/outcome.json`;
const run = spawnSync(
  "java",
  [
    "-Xmx2g",
    "-jar",
    JAR,
    ...files.map((f) => f.file),
    "-version",
    "4.0.1",
    "-ig",
    "hl7.fhir.au.ps#1.0.0",
    "-tx",
    TX,
    "-output",
    out,
  ],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
const version = /FHIR Validation tool Version (\S+)/.exec(run.stdout)?.[1] ?? "unknown";
const bundle = JSON.parse(readFileSync(out, "utf8")) as Bundle;

let errors = 0;
const warnings = new Map<string, number>();
const rows: string[] = [];
for (const entry of bundle.entry ?? []) {
  const oc = entry.resource as OperationOutcome;
  const path = oc.extension?.find((e) => e.url.endsWith("operationoutcome-file"))?.valueString ?? "";
  const f = files.find((x) => path.endsWith(x.file.split("/").pop()!));
  const errs = oc.issue.filter((i) => i.severity === "error" || i.severity === "fatal");
  errors += errs.length;
  rows.push(`| ${f?.label ?? path} | ${errs.length} |`);
  for (const e of errs) console.error(`${f?.file}: ${e.expression?.[0] ?? ""}: ${e.details?.text}`);
  for (const w of oc.issue.filter((i) => i.severity === "warning")) {
    const t = (w.details?.text ?? "")
      .replace(/'[^']*'/g, "'…'")
      .replace(/\d+/g, "N")
      .slice(0, 160);
    warnings.set(t, (warnings.get(t) ?? 0) + 1);
  }
}
const top = [...warnings].sort((a, b) => b[1] - a[1]);
writeFileSync(
  "docs/validation/au-ps.md",
  `# AU Patient Summary validation

Generated by \`npm run validate:ps\`. Validator ${version}, \`hl7.fhir.au.ps#1.0.0\`, terminology server ${TX}.
Each document is built by \`src/lib/ps/build.ts\` from a patient on the local HAPI server.

| Document | Errors (error or fatal) |
|---|---|
${rows.join("\n")}

**Total errors: ${errors}**

## Warnings by count (messages generalised)

${top.length ? top.map(([t, n]) => `- ${n} × ${t}`).join("\n") : "None."}
`,
);
console.log(`errors: ${errors}; report: docs/validation/au-ps.md`);
process.exit(errors ? 1 : 0);
