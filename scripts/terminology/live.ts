// Runs the M10 acceptance terms against a live terminology server and writes docs/validation/terminology.md.
// Usage: npm run test:terminology     (TERMINOLOGY_BASE_URL, default the CSIRO test endpoint)
import { writeFileSync } from "node:fs";
import targets from "../../services/nlp/targets.json" with { type: "json" };
import { type Config, codeTerm } from "../../src/lib/terminology/client.ts";
import { ACCEPTANCE, NONSENSE } from "../../src/lib/terminology/acceptance.ts";

const base = process.env.TERMINOLOGY_BASE_URL ?? "https://tx.ontoserver.csiro.au/fhir";
const cfg: Config = { backend: "csiro", base };
const rows: string[] = [];
const mismatches: string[] = [];
let edition: string | null = null;
for (const [query, want] of ACCEPTANCE) {
  const r = await codeTerm(query, cfg, targets.targets);
  edition ??= r.edition;
  const ok = r.best?.code === want;
  if (!ok) mismatches.push(`${query}: expected ${want}, got ${r.best?.code ?? "no code"}`);
  rows.push(
    `| ${query} | ${want} | ${r.best ? `${r.best.code} ${r.best.display}` : "no code"} | ${r.best?.confidence ?? "-"} | ${ok ? "ok" : "MISMATCH"} |`,
  );
}
const nonsense = await codeTerm(NONSENSE, cfg, targets.targets);
const nonsenseOk = nonsense.best === null;
if (!nonsenseOk) mismatches.push(`${NONSENSE}: expected no code, got ${nonsense.best?.code}`);
rows.push(
  `| ${NONSENSE} | no code | ${nonsense.best ? nonsense.best.code : "no code"} | - | ${nonsenseOk ? "ok" : "MISMATCH"} |`,
);

writeFileSync(
  "docs/validation/terminology.md",
  `# Terminology coding: live run

Generated by \`npm run test:terminology\` on ${new Date().toISOString().slice(0, 10)}.

- Backend: ${base} (Ontoserver, public test endpoint; no credentials, no guarantee of availability)
- Edition: ${edition ?? "unknown"}
- Query: \`ValueSet/$expand\` over \`${"http://snomed.info/sct/32506021000036107"}?fhir_vs=ecl/<404684003\` (clinical findings), ranked by \`src/lib/terminology/rank.ts\`

| Query | Expected | Top-1 | Confidence | Result |
|---|---|---|---|---|
${rows.join("\n")}

**Mismatches: ${mismatches.length}**${mismatches.length ? "\n\n" + mismatches.map((m) => `- ${m}`).join("\n") : ""}

SNOMED CT-AU is used through this server; see the attribution in the app footer. ICD-10-AM is not included (IHACPA licence).
`,
);
console.log(mismatches.length ? mismatches.join("\n") : "all terms matched");
process.exit(mismatches.length ? 1 : 0);
