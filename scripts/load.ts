// Loads data/cohort into a FHIR server. Shared resources first, then each patient as one
// transaction of PUTs by id, so loading twice changes nothing.
// Usage: npm run load [-- --limit 3]      (target: the local Docker HAPI on localhost:8080)
// Cloud: LOAD_BASE=https://<service>/fhir LOAD_TOKEN=$(gcloud auth print-identity-token) npm run load
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Bundle } from "fhir/r4";

const BASE = process.env.LOAD_BASE ?? "http://localhost:8080/fhir";
const AUTH: Record<string, string> = process.env.LOAD_TOKEN
  ? { Authorization: `Bearer ${process.env.LOAD_TOKEN}` }
  : {};
const COHORT = "data/cohort";
const CONCURRENCY = 2;
const TYPES = [
  "Patient",
  "Encounter",
  "Condition",
  "Observation",
  "DiagnosticReport",
  "DocumentReference",
  "MedicationRequest",
  "Medication",
  "AllergyIntolerance",
  "Immunization",
  "Procedure",
  "Organization",
  "Practitioner",
  "Location",
];

const limitArg = process.argv.indexOf("--limit");
const limit = limitArg > 0 ? Number(process.argv[limitArg + 1]) : Infinity;

async function waitForServer() {
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch(`${BASE}/metadata`, { headers: AUTH, signal: AbortSignal.timeout(5000) })).ok) return;
    } catch {}
    await new Promise((r) => setTimeout(r, 5000));
  }
  throw new Error(`No FHIR server at ${BASE}. Start it with: docker compose up -d`);
}

type Result = { file: string; ok: boolean; seconds: number; detail: string };

async function post(file: string): Promise<Result> {
  const started = Date.now();
  const done = (ok: boolean, detail: string) => ({
    file,
    ok,
    seconds: Math.round((Date.now() - started) / 100) / 10,
    detail,
  });
  try {
    const res = await fetch(BASE, {
      method: "POST",
      headers: { ...AUTH, "Content-Type": "application/fhir+json" },
      body: readFileSync(join(COHORT, file)),
      signal: AbortSignal.timeout(300_000),
    });
    const body = (await res.json()) as Bundle;
    if (!res.ok) return done(false, `HTTP ${res.status}: ${JSON.stringify(body).slice(0, 300)}`);
    const failed = (body.entry ?? []).filter((e) => !/^20[01]/.test(e.response?.status ?? ""));
    return done(
      failed.length === 0,
      failed.length ? `${failed.length} entries failed` : `${body.entry?.length ?? 0} resources`,
    );
  } catch (e) {
    return done(false, String(e));
  }
}

async function count(type: string): Promise<number> {
  const bundle = (await (await fetch(`${BASE}/${type}?_summary=count`, { headers: AUTH })).json()) as Bundle;
  return bundle.total ?? -1;
}

function databaseBytes(): number | undefined {
  try {
    return Number(
      execSync(`docker compose exec -T db psql -U hapi -d hapi -Atc "select pg_database_size('hapi')"`, {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim(),
    );
  } catch {
    return undefined; // not the Docker database
  }
}

await waitForServer();
const patientFiles = readdirSync(COHORT)
  .filter((f) => f.endsWith(".json") && !f.startsWith("_") && f !== "manifest.json")
  .slice(0, limit);

const results: Result[] = [await post("_shared.json")]; // organisations, practitioners, locations first
const queue = [...patientFiles];
await Promise.all(
  Array.from({ length: CONCURRENCY }, async () => {
    for (let file = queue.shift(); file; file = queue.shift()) {
      const result = await post(file);
      console.log(`${result.ok ? "ok  " : "FAIL"} ${file} (${result.seconds}s) ${result.detail}`);
      results.push(result);
    }
  }),
);

const counts = Object.fromEntries(await Promise.all(TYPES.map(async (t) => [t, await count(t)] as const)));
const bytes = databaseBytes();
const failed = results.filter((r) => !r.ok);
const report = `# Load report (${BASE})

Generated by \`npm run load\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC.

- Bundles loaded: ${results.length - failed.length} of ${results.length}${failed.length ? ` — failed: ${failed.map((f) => f.file).join(", ")}` : ""}
- Database size: ${bytes === undefined ? "not measured" : `${(bytes / 1e6).toFixed(1)} MB`} (budget 250 MB)

| Resource | Count on server |
|---|---|
${TYPES.map((t) => `| ${t} | ${counts[t]} |`).join("\n")}
`;
mkdirSync("docs/validation", { recursive: true });
writeFileSync("docs/validation/load-local.md", report);
console.log(report);
if (failed.length) process.exit(1);
